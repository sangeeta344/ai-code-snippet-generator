"""
backend/validator.py
 
Backend Validation module for the Req2Py hackathon project.
 
This module is responsible ONLY for validating Python source code that
is generated by the LLM pipeline. It checks:
 
    1. Syntax validity (using the built-in `ast` module).
    2. Basic structural statistics (functions, classes, imports, loops,
       conditionals).
 
It does NOT:
    - Run a Flask API.
    - Talk to Ollama or any LLM.
    - Execute any generated code (no eval/exec/subprocess).
    - Perform safety/security checks (that belongs in safety.py).
 
Other modules (e.g. pipeline.py) should import and call `validate_code()`
as the single entry point for validating a piece of generated Python code.
"""
 
import ast
from typing import Any, Dict, List
 
 
def validate_syntax(code: str) -> Dict[str, Any]:
    """
    Check whether a string of Python source code is syntactically valid.
 
    This uses `ast.parse()` under the hood. It never executes the code
    (no eval/exec) and never raises an exception back to the caller -
    any SyntaxError is caught and reported as data.
 
    Args:
        code: The Python source code to check, as a string.
 
    Returns:
        A dictionary with the following keys:
            - valid (bool): True if the code parses without errors.
            - error_type (str | None): The exception class name, e.g.
              "SyntaxError", or None if the code is valid.
            - error_message (str | None): A human-readable error message,
              or None if the code is valid.
            - line (int | None): The line number where the error occurred,
              or None if the code is valid.
            - column (int | None): The column offset where the error
              occurred, or None if the code is valid.
    """
    if not isinstance(code, str):
        return {
            "valid": False,
            "error_type": "TypeError",
            "error_message": "Input code must be a string.",
            "line": None,
            "column": None,
        }
 
    try:
        ast.parse(code)
        return {
            "valid": True,
            "error_type": None,
            "error_message": None,
            "line": None,
            "column": None,
        }
    except SyntaxError as exc:
        return {
            "valid": False,
            "error_type": type(exc).__name__,
            "error_message": str(exc.msg) if exc.msg else str(exc),
            "line": exc.lineno,
            "column": exc.offset,
        }
    except (ValueError, TypeError) as exc:
        # ast.parse can raise ValueError for things like null bytes,
        # and TypeError for unexpected input. Handle gracefully.
        return {
            "valid": False,
            "error_type": type(exc).__name__,
            "error_message": str(exc),
            "line": None,
            "column": None,
        }
 
 
def validate_structure(code: str) -> Dict[str, Any]:
    """
    Parse Python source code and collect basic structural statistics.
 
    Counts top-level and nested occurrences of functions, classes,
    imports, loops, and conditionals by walking the AST.
 
    Args:
        code: The Python source code to analyze, as a string.
 
    Returns:
        A dictionary with the following keys:
            - valid (bool): True if the code could be parsed at all.
            - functions (int): Number of function definitions
              (including async functions).
            - classes (int): Number of class definitions.
            - imports (int): Number of import statements
              (each `import`/`from...import` line counts as one).
            - loops (int): Number of `for` and `while` loops.
            - conditionals (int): Number of `if` statements.
            - error_message (str | None): Present and non-None only when
              the code could not be parsed.
    """
    try:
        tree = ast.parse(code)
    except (SyntaxError, ValueError, TypeError) as exc:
        # Structural validation depends on a valid AST. If parsing
        # fails, return a meaningful result instead of crashing.
        return {
            "valid": False,
            "functions": 0,
            "classes": 0,
            "imports": 0,
            "loops": 0,
            "conditionals": 0,
            "error_message": f"Could not analyze structure: {exc}",
        }
 
    functions = 0
    classes = 0
    imports = 0
    loops = 0
    conditionals = 0
 
    for node in ast.walk(tree):
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
            functions += 1
        elif isinstance(node, ast.ClassDef):
            classes += 1
        elif isinstance(node, (ast.Import, ast.ImportFrom)):
            imports += 1
        elif isinstance(node, (ast.For, ast.AsyncFor, ast.While)):
            loops += 1
        elif isinstance(node, ast.If):
            conditionals += 1
 
    return {
        "valid": True,
        "functions": functions,
        "classes": classes,
        "imports": imports,
        "loops": loops,
        "conditionals": conditionals,
        "error_message": None,
    }
 
 
def validate_code(code: str) -> Dict[str, Any]:
    """
    Main entry point for validating generated Python code.
 
    Runs syntax validation first. If the code has a syntax error,
    structural validation is skipped and the syntax error is reported.
    If the syntax is valid, structural validation is performed as well.
 
    This function is designed to be imported and called directly by
    pipeline.py (or any other module) as the single validation entry
    point for the backend.
 
    Args:
        code: The Python source code to validate, as a string.
 
    Returns:
        A dictionary with the following keys:
            - valid (bool): Overall validity of the code (True only if
              the syntax is valid).
            - syntax (dict): The result of validate_syntax(code).
            - structure (dict | None): The result of validate_structure(code),
              or None if syntax validation failed (structure is skipped).
            - errors (list[str]): Human-readable error messages, if any.
            - warnings (list[str]): Non-fatal observations about the code
              (e.g. no functions defined). Empty if nothing to note.
    """
    errors: List[str] = []
    warnings: List[str] = []
 
    syntax_result = validate_syntax(code)
 
    if not syntax_result["valid"]:
        errors.append(
            f"{syntax_result['error_type']}: {syntax_result['error_message']} "
            f"(line {syntax_result['line']}, column {syntax_result['column']})"
        )
        return {
            "valid": False,
            "syntax": syntax_result,
            "structure": None,
            "errors": errors,
            "warnings": warnings,
        }
 
    structure_result = validate_structure(code)
 
    # Structural validation should always succeed here since syntax
    # already passed, but we guard defensively just in case.
    if not structure_result["valid"]:
        errors.append(structure_result["error_message"] or "Unknown structural error.")
 
    # A few simple, non-fatal warnings that can help the pipeline / user.
    if structure_result["valid"]:
        if structure_result["functions"] == 0 and structure_result["classes"] == 0:
            warnings.append("No functions or classes were defined in this code.")
        if not code.strip():
            warnings.append("The provided code is empty.")
 
    return {
        "valid": syntax_result["valid"] and structure_result["valid"],
        "syntax": syntax_result,
        "structure": structure_result,
        "errors": errors,
        "warnings": warnings,
    }
 
 
if __name__ == "__main__":
    # Simple demonstration of the three public functions.
    # This block only analyzes strings with `ast` - it never executes
    # any of the sample code below.
 
    print("=== 1. Valid Python code ===")
    valid_sample = "x = 1\ny = 2\nprint(x + y)\n"
    result_1 = validate_code(valid_sample)
    print(result_1)
 
    print("\n=== 2. Invalid Python code (syntax error) ===")
    invalid_sample = "def broken(:\n    pass\n"
    result_2 = validate_code(invalid_sample)
    print(result_2)
 
    print("\n=== 3. Code with a function and an import ===")
    structured_sample = (
        "import math\n\n"
        "def compute_area(radius):\n"
        "    if radius > 0:\n"
        "        return math.pi * radius ** 2\n"
        "    else:\n"
        "        return 0\n"
    )
    result_3 = validate_code(structured_sample)
    print(result_3)
 